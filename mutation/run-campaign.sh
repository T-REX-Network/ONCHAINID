#!/usr/bin/env bash
#
# Mutation-testing campaign runner for ONCHAINID.
#
# Generates Solidity mutants of the security-critical contracts via Gambit, then
# for each mutant: swaps it into the source tree, runs `forge test`, observes
# whether any test fails (mutant killed) or all pass (mutant survived). Surviving
# mutants are precise prompts for missing tests — each one names a single line
# you can change without any test catching it.
#
# Usage:
#   ./mutation/run-campaign.sh                 # full run
#   ./mutation/run-campaign.sh --generate-only # write mutants, skip testing
#   ./mutation/run-campaign.sh --resume        # skip mutants already in report
#   GAMBIT=/path/to/gambit ./mutation/run-campaign.sh
#   EXCLUDE_TESTS='testFuzz_|_neverReverts' ./mutation/run-campaign.sh   # override default filter
#   Default filter excludes Tier 1 finding-trackers (_neverReverts, _notAdvertised, _FINDING)
#   OUTDIR=/tmp/g REPORT=/tmp/r.tsv ./mutation/run-campaign.sh   # custom paths
#
# Requires: gambit, forge, jq, solc (matching foundry.toml's solc_version)
#
# Expected runtime: a full campaign over the contracts in mutation/gambit_conf.json generates
#   ~300–700 mutants; each takes ~5–10s under `forge test --summary` (no compile cache
#   between mutants), so plan for 30–90 minutes wall time. Use `gambit mutate --num_mutants N`
#   on the conf for faster iteration during development.
#
# Output:
#   gambit_out/        — mutants generated by gambit (one subdir per mutant)
#   mutation-report.tsv — TSV of every mutant tested: id, file, op, line, result
#
set -euo pipefail

GAMBIT="${GAMBIT:-gambit}"
CONF="${CONF:-mutation/gambit_conf.json}"
OUTDIR="${OUTDIR:-gambit_out}"
REPORT="${REPORT:-mutation-report.tsv}"
GENERATE_ONLY=0
RESUME=0

for arg in "$@"; do
    case "$arg" in
        --generate-only) GENERATE_ONLY=1 ;;
        --resume) RESUME=1 ;;
        -h|--help)
            sed -n '3,21p' "$0"
            exit 0
            ;;
        *)
            echo "unknown flag: $arg" >&2
            exit 1
            ;;
    esac
done

# ---- Tool checks ----

require_tool() {
    if ! command -v "$1" >/dev/null 2>&1; then
        echo "ERROR: $1 not in PATH. $2" >&2
        exit 1
    fi
}

require_tool "$GAMBIT" "Install from https://github.com/Certora/gambit (cargo install gambit-mutator) or set GAMBIT=/path/to/binary."
require_tool forge "Install Foundry: https://book.getfoundry.sh/getting-started/installation"
require_tool jq "brew install jq (used to parse gambit_results.json)"
require_tool solc "brew install ethereum (must match foundry.toml solc_version)"

# ---- Repo root sanity ----

if [ ! -f "foundry.toml" ] || [ ! -f "$CONF" ]; then
    echo "ERROR: run from repo root (where foundry.toml and $CONF live)." >&2
    exit 1
fi

# ---- Generate mutants ----

if [ ! -d "$OUTDIR/mutants" ] || [ "${REGENERATE:-0}" = "1" ]; then
    echo "[campaign] generating mutants → $OUTDIR/"
    rm -rf "$OUTDIR"
    "$GAMBIT" mutate --json "$CONF" --outdir "$OUTDIR"
else
    echo "[campaign] reusing existing mutants in $OUTDIR/ (set REGENERATE=1 to redo)"
fi

if [ "$GENERATE_ONLY" = "1" ]; then
    n=$(find "$OUTDIR/mutants" -mindepth 1 -maxdepth 1 -type d | wc -l | tr -d ' ')
    echo "[campaign] generated $n mutants — exiting (--generate-only)"
    exit 0
fi

# ---- Pre-flight: tests must be green before we start ----

# Tests that fail on the unmutated source (e.g. Tier 1 finding-trackers) must be excluded
# so a mutant's "kill" is judged against passing tests only. Override via env if you need
# to tweak the pattern.
EXCLUDE_TESTS="${EXCLUDE_TESTS:-_neverReverts|_notAdvertised|_FINDING}"

# Helper: returns the number of failing tests under the exclude filter.
#
# Hardenings learned during earlier runs:
#  - `forge test` can exit non-zero from a compile error, a panic, or a transient internal
#    failure. In those cases "Encountered a total of N failing tests" never gets printed, so
#    a naive sed parse returns empty → 0 → mutant marked "survived" even though the mutant
#    broke the build. We separate the explicit-count case from the fallback: if the explicit
#    line is absent AND forge exited non-zero, count it as a kill (something demonstrably
#    broke).
#  - `set -e` does NOT trip on `[ ... ]` inside an `if`, so a bad mutant_failures value
#    silently routed to the `else` branch. The new logic produces a guaranteed-numeric value.
count_failures() {
    local out
    local forge_exit=0
    out=$(forge test --summary --no-match-test "$EXCLUDE_TESTS" 2>&1) || forge_exit=$?
    local n
    n=$(printf '%s' "$out" | sed -nE 's/.*Encountered a total of ([0-9]+) failing tests.*/\1/p' | tail -n1)
    if [ -z "$n" ]; then
        # No explicit count parsed. If forge exited non-zero, treat as "all hell broke loose"
        # — the mutant disrupted compilation or runtime. Use a large sentinel so the kill
        # comparison ($n > BASELINE_FAILURES) reliably trips.
        if [ "$forge_exit" != "0" ]; then
            n=999
        else
            n=0
        fi
    fi
    printf '%s' "$n"
}

echo "[campaign] pre-flight: counting baseline failures (filter: $EXCLUDE_TESTS)"
BASELINE_FAILURES=$(count_failures)
echo "[campaign] baseline failures: $BASELINE_FAILURES"
if [ "$BASELINE_FAILURES" != "0" ]; then
    echo "WARNING: $BASELINE_FAILURES tests fail on the unmutated source even after exclude." >&2
    echo "         Mutants will be killed only when they introduce ADDITIONAL failures." >&2
fi

# ---- Iterate mutants ----

if [ "$RESUME" = "0" ] || [ ! -f "$REPORT" ]; then
    printf "mutant_id\tfile\toperator\tline\tresult\tdescription\n" > "$REPORT"
fi

# Pre-flight: refuse to start if any tracked contracts file has local modifications.
# `git checkout` is our source-of-truth for restoration, so an unclean working tree means
# we could overwrite real work between iterations.
if ! git diff --quiet -- contracts/ 2>/dev/null; then
    echo "ERROR: contracts/ has uncommitted modifications. Commit or stash before running." >&2
    echo "       Restoration uses 'git checkout -- <file>', which would discard those changes." >&2
    git diff --stat -- contracts/ >&2
    exit 1
fi

# Trap: restore the in-flight target via git so an interrupt never leaves the source corrupted.
# `git checkout -- <path>` is idempotent and deterministic — unlike the previous mv-from-.bak
# scheme, which could silently leave a mutant in place when the .bak went missing.
INFLIGHT_TGT=""
restore_inflight() {
    if [ -n "$INFLIGHT_TGT" ]; then
        git checkout -- "$INFLIGHT_TGT" 2>/dev/null || true
        echo "[campaign] restored $INFLIGHT_TGT via git checkout" >&2
    fi
}
trap restore_inflight EXIT INT TERM

# gambit_results.json (if Gambit emits it) has metadata per mutant.
RESULTS_JSON="$OUTDIR/gambit_results.json"
have_metadata=0
if [ -f "$RESULTS_JSON" ]; then
    have_metadata=1
fi

total=0
killed=0
survived=0
skipped=0

# Portable: avoid `mapfile` (bash 4+ only — macOS ships bash 3.2).
mutant_dirs_list=$(find "$OUTDIR/mutants" -mindepth 1 -maxdepth 1 -type d | sort -V)

while IFS= read -r mutant_dir; do
    [ -z "$mutant_dir" ] && continue
    id=$(basename "$mutant_dir")

    if [ "$RESUME" = "1" ] && awk -v i="$id" -F'\t' 'NR>1 && $1==i {found=1; exit} END{exit !found}' "$REPORT"; then
        skipped=$((skipped + 1))
        continue
    fi

    # Find the single .sol file inside the mutant directory (Gambit mirrors the
    # source path from --sourceroot under the mutant dir).
    mutant_file=$(find "$mutant_dir" -name '*.sol' -type f | head -n1)
    if [ -z "$mutant_file" ]; then
        echo "[campaign] $id: no .sol found, skipping"
        continue
    fi

    # The path inside the mutant dir mirrors the repo-relative source path.
    # `mutant_dir` ends with a trailing slash from the `*/` glob; strip it before prefix-removal.
    mutant_dir_clean="${mutant_dir%/}"
    target_file="${mutant_file#"$mutant_dir_clean"/}"
    if [ ! -f "$target_file" ]; then
        echo "[campaign] $id: target $target_file does not exist (path mirror issue), skipping"
        continue
    fi

    operator=""
    line=""
    description=""
    if [ "$have_metadata" = "1" ]; then
        # gambit_results.json entries: { id: "N", description: "OperatorName", diff: "--- ...\n@@ -LINE,...", name, original, sourceroot }
        # `operator` ← description; `line` ← parse first hunk header from the diff.
        meta=$(jq -r --arg id "$id" '
            .[] | select((.id|tostring)==$id)
            | [.description, (try (.diff | capture("@@ -(?<l>[0-9]+)").l) catch ""), .description]
            | @tsv
        ' "$RESULTS_JSON" 2>/dev/null || true)
        if [ -n "$meta" ]; then
            operator=$(printf '%s' "$meta" | cut -f1)
            line=$(printf '%s' "$meta" | cut -f2)
            description=$(printf '%s' "$meta" | cut -f3 | tr '\t\n' '  ')
        fi
    fi

    # Swap the mutant in. No .bak needed — we'll restore from git.
    INFLIGHT_TGT="$target_file"
    cp "$mutant_file" "$target_file"

    mutant_failures=$(count_failures)

    # Restore via git (deterministic; never silently fails).
    git checkout -- "$target_file"
    # Belt-and-braces: verify the restore left the working tree clean for this file.
    # If for any reason it didn't, abort so we don't pollute subsequent iterations.
    if ! git diff --quiet -- "$target_file"; then
        echo "[campaign] FATAL: $target_file did not restore cleanly after mutant $id" >&2
        git diff --stat -- "$target_file" >&2
        exit 1
    fi
    INFLIGHT_TGT=""

    # A mutant is "killed" when it introduces ADDITIONAL test failures beyond the baseline.
    if [ "$mutant_failures" -gt "$BASELINE_FAILURES" ]; then
        result=killed
        killed=$((killed + 1))
    else
        result=survived
        survived=$((survived + 1))
    fi

    total=$((total + 1))
    printf "%s\t%s\t%s\t%s\t%s\t%s\n" "$id" "$target_file" "$operator" "$line" "$result" "$description" >> "$REPORT"
    printf "[%d] %-6s %s:%s op=%s (%s)\n" "$total" "$id" "$target_file" "$line" "$operator" "$result"
done <<< "$mutant_dirs_list"

# ---- Summary ----

echo
echo "==========================="
echo " mutation campaign summary"
echo "==========================="
echo "  tested:   $total"
echo "  killed:   $killed"
echo "  survived: $survived"
echo "  skipped:  $skipped (resumed runs)"
if [ "$total" -gt 0 ]; then
    rate=$(awk -v k="$killed" -v t="$total" 'BEGIN{printf "%.1f", (k/t)*100}')
    echo "  kill rate: ${rate}%"
fi
echo
echo "Survivors (each one is a missing test):"
awk -F'\t' 'NR>1 && $5=="survived" {printf "  %s  %s:%s  op=%s  %s\n", $1, $2, $4, $3, $6}' "$REPORT" | head -50
n_surv=$(awk -F'\t' 'NR>1 && $5=="survived"' "$REPORT" | wc -l | tr -d ' ')
if [ "$n_surv" -gt 50 ]; then
    echo "  ... and $((n_surv - 50)) more — see $REPORT"
fi
